/**
 * 应用语言
 * @param {"zh"|"en"} lang
 */
function applyLanguage(lang) {
    if (!i18n[lang]) lang = "zh";
    document.documentElement.lang = (lang === "zh") ? "zh-CN" : "en";
    document.documentElement.setAttribute("data-lang", lang);

    const dict = i18n[lang];
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });

    // 更新语言按钮显示
    const btn = document.getElementById("langSwitch");
    if (btn) {
        btn.querySelector(".lang-active").textContent = (lang === "zh") ? "中" : "EN";
        btn.querySelector(".lang-alt").textContent = (lang === "zh") ? "EN" : "中";
    }

    // 持久化
    try { localStorage.setItem("by-lang", lang); } catch (e) {}
}

/**
 * 切换语言
 */
function toggleLanguage() {
    const current = document.documentElement.getAttribute("data-lang") || "zh";
    const next = (current === "zh") ? "en" : "zh";
    applyLanguage(next);
}

/**
 * 初始化：从 localStorage 读取上次选择
 */
function initLanguage() {
    let saved = "zh";
    try { saved = localStorage.getItem("by-lang") || "zh"; } catch (e) {}
    if (saved !== "zh" && saved !== "en") saved = "zh";
    applyLanguage(saved);
}

// 暴露到全局
window.applyLanguage = applyLanguage;
window.toggleLanguage = toggleLanguage;

// DOM Ready
if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initLanguage);
} else {
    initLanguage();
}
